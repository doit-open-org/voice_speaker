/**
 * 「AI生成」标识。
 *
 * ## 为什么有这个东西
 *
 * 2026-08 微信审核：「你的小程序涉及提供文本深度合成技术（如：AI创作）等
 * 相关服务，请补充选择：深度合成-AI创作类目，并在AI生成页面增加显著说明
 * "AI生成、人工智能生成"或同等含义字样。」
 *
 * 这是《互联网信息服务深度合成管理规定》第十七条的落地要求，不是可选项。
 *
 * ## 为什么不是只改导航栏标题
 *
 * 上一轮已经把「(AI生成)」塞进了 adCopy / longTextDubbing / dialogueDubbing
 * 的 navigationBarTitleText，**然后审核又打回来了**。导航栏标题算不上「显著」，
 * 而且真正要标的是**生成出来的内容**，不是页面的名字。
 * 所以这一版做成页面里的一条实体说明，跟内容挨着放。
 *
 * ## 挂在哪
 *
 * 凡是「用户点一下、机器产出内容」的页面都要挂：
 * 文案生成（adCopy / adCopyResult）、语音合成（index / generate /
 * longTextDubbing / dialogueDubbing）、音色转换（voiceConvert）。
 * 判断标准很简单——**产出物不是用户自己写的/录的，就得标**。
 * 新加同类功能页时一并挂上，tests 里有一条用例守着这份清单。
 */
